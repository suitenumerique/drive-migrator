class Base(
    GeneralMixin,
    DatabaseMixin,
    CacheMixin,
    StorageMixin,
    ApplicationMixin,
    DRFMixin,
    I18nMixin,
    EmailMixin,
    CorsMixin,
    LoggingMixin,
    ObservabilityMixin,
    CeleryMixin,
    OIDCMixin,
    MigrationBackendsMixin,
    ResanaMixin,
    DriveMixin,
    OsmoseMixin,
    Configuration,
):
    """
    This is the base configuration every configuration (aka environment) should inherit from.

    The actual settings are grouped by domain into the mixins of the
    ``main.configurations`` package and composed here; ``Configuration`` is kept
    last because django-configurations merges the base in reverse order, so
    listed it first would override the mixin settings with Django's default.
     To configure a third-party application, add (or extend) a mixin
    in ``main/configurations`` rather than growing this file. See
    ``docs/backend-settings.md`` for details.

    It depends on an environment variable that SHOULD be defined:

    * DJANGO_SECRET_KEY

    You may also want to override default configuration by setting the following environment
    variables:

    * DJANGO_SENTRY_DSN
    * POSTHOG_KEY
    * POSTHOG_HOST
    * DB_NAME
    * DB_HOST
    * DB_PASSWORD
    * DB_USER
    """

    # pylint: disable=invalid-name
    @property
    def ENVIRONMENT(self):
        """Environment in which the application is launched."""
        return self.__class__.__name__.lower()

    # pylint: disable=invalid-name
    @property
    def RELEASE(self):
        """
        Return the release information.

        Delegate to the module function to enable easier testing.
        """
        return get_release()

    @classmethod
    def post_setup(cls):
        """Post setup configuration.
        This is the place where you can configure settings that require other
        settings to be loaded.
        """
        super().post_setup()

        # The SENTRY_DSN setting should be available to activate sentry for an environment
        if cls.SENTRY_DSN is not None:
            sentry_sdk.init(
                dsn=cls.SENTRY_DSN,
                environment=cls.__name__.lower(),
                release=get_release(),
                integrations=[DjangoIntegration()],
            )

            # Add the application name to the Sentry scope
            scope = sentry_sdk.get_global_scope()
            scope.set_tag("application", "backend")

            # Ignore the logs added by the DockerflowMiddleware
            ignore_logger("request.summary")

        posthog.api_key = cls.POSTHOG_KEY
        posthog.host = cls.POSTHOG_HOST


