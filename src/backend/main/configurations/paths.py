"""Shared filesystem paths and release helper for the settings package.

These values are imported both by ``main.settings`` and by the configuration
mixins, so they live in a dependency-free module to avoid import cycles.
"""

import json
import os

# Build paths inside the project like this: BASE_DIR / 'subdir'.
# This module lives in ``main/configurations/``, so three ``dirname`` calls are
# needed to climb back up to the backend root (where ``settings.py`` used to
# compute ``BASE_DIR`` with two).
BASE_DIR = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA_DIR = os.path.join("/", "data")


def get_release():
    """
    Get the current release of the application

    By release, we mean the release from the version.json file à la Mozilla [1]
    (if any). If this file has not been found, it defaults to "NA".

    [1]
    https://github.com/mozilla-services/Dockerflow/blob/master/docs/version_object.md
    """
    # Try to get the current release from the version.json file generated by the
    # CI during the Docker image build
    try:
        with open(os.path.join(BASE_DIR, "version.json"), encoding="utf8") as version:
            return json.load(version)["version"]
    except FileNotFoundError:
        return "NA"  # Default: not available
